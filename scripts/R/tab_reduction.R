# ==============================================================================
# tab_reduction.R — Table: genome-wide reduction at the measured V_A, one model family
# ==============================================================================
# Run from the repo root:   Rscript scripts/R/tab_reduction.R
# Reads only through load_data.R. Writes manuscript/tables/tab_reduction.tex.
#
# Per population: kappa (Model B; 1 without a pair bond), V_A posterior mode and 95% HPD,
# the unlinked N_e/N at first order, 1/(1 + 4 kappa V_A), and under the multiplicative map
# (exact, Appendix B eq:B_moments) and its upper bound on the reduction, exp(-4 kappa_mult V_A).
# Where pi and a census exist: the observed diversity ratio delta = pi / (4 mu N_c), as log10, and the
# smallest V_A that could account for it, ln(1/delta) / (4 kappa_mult).
# ==============================================================================
suppressPackageStartupMessages(library(dplyr))
source("scripts/R/load_data.R")

pops <- load_populations("va")
obs <- load_diversity()
fmt <- function(x, d = 2) ifelse(is.na(x), "--", formatC(x, format = "f", digits = d))
sig <- function(x) ifelse(is.na(x), "--", formatC(signif(x, 2), format = "fg", big.mark = ","))
sig2 <- function(x) ifelse(is.na(x), "--", formatC(x, digits = 2, format = "fg", flag = "#"))

d <- pops %>%
  left_join(obs %>% select(code, pi_obs, pi_lit, log10_Nc), by = "code") %>%
  mutate(pair = pair_bond == "social_monogamy",
         pi_any = coalesce(pi_obs, pi_lit),
         delta = pi_any / (4 * mu_direct * 10^log10_Nc),
         # Soay: Buffalo's Ovis aries census is domestic sheep (Methods)
         delta = if_else(code == "SSH", NA_real_, delta),
         ne_first = 1 / reduction_G1,
         ne_mult = 1 / reduction_mult,
         ne_bound = 1 / reduction_mult_bound,
         va_need = vamax_mult(delta, kappa_mult_bound(pair)),
         species_lab = sub(" \\(.*\\)$", "", common_name),
         # "Species (Location)" as in the figures, without the country and the
         # generic part of the place name, so the table fits the text width
         site = sub(",.*$", "", sub("^tiritiri", "Tiritiri", location)),
         site = sub(" (Island|National Park|Crater)$", "", site),
         label = sprintf("%s (%s)", species_lab, site)) %>%
  arrange(desc(pair), desc(va_mode))

# delta as log10 (user, 2026-10-26: no fractions), with a true minus sign
row_tex <- function(x) with(x, sprintf("%s & %s & %s (%s--%s) & %s & %s & %s & %s & %s \\\\",
  label, fmt(kappa), fmt(va_mode, 3), fmt(va_hpd95_lo, 3), fmt(va_hpd95_hi, 2),
  sig2(ne_first), sig2(ne_mult), sig2(ne_bound),
  ifelse(is.na(delta), "--", sprintf("$%s$", fmt(log10(delta)))), fmt(va_need)))
group_head <- function(txt) sprintf("\\multicolumn{8}{l}{\\textit{%s}} \\\\", txt)
rows <- c(group_head("Social monogamy"), row_tex(filter(d, pair)),
          "\\addlinespace", group_head("Random mating"), row_tex(filter(d, !pair)))

tex <- c(
  "% Generated by scripts/R/tab_reduction.R from data/processed/ -- do not edit by hand.",
  "\\begin{table}[h!]",
  "\\centering",
  "\\caption{Genome-wide reduction in effective size at the measured $V_A$, under multiplicative fitness ($w \\propto e^{z}$). $\\hat{V}_A$: posterior mode and 95\\% HPD interval (Bonnet et al.\\ 2022). Populations are grouped by mating system and listed by species and study site (countries as in Figure~\\ref{fig:unlinked}). $N_e/N$ at the posterior mode: the small-variance approximation, $1/(1+4\\kappa V_A)$; the multiplicative model (Appendix~B); and the multiplicative bound, $e^{-4\\kappa_\\text{max}V_A}$ (Barton and Etheridge 2011; Weissman and Barton 2012). $\\log_{10}\\delta$: observed diversity ratio $\\delta = \\pi/(4\\mu N_c)$, on a log scale, where $\\pi$ and a census exist (Methods); $-4$ means diversity $10^{-4}$ of its neutral expectation. $V_A$ needed: the least variance that could account for $\\delta$, $V_{A,\\delta} = \\ln(1/\\delta)/(4\\kappa_\\text{max})$ (Equation~\\eqref{eq:vamax_mult}).}",
  "\\label{tab:reduction}",
  "\\scriptsize",
  "\\setlength{\\tabcolsep}{3.5pt}",
  "\\begin{tabular}{lrrrrrrr}",
  "\\toprule",
  " & & & \\multicolumn{3}{c}{$N_e/N$} & & $V_A$ \\\\",
  "\\cmidrule(lr){4-6}",
  "Population & $\\kappa$ & $\\hat{V}_A$ (95\\% HPD) & approx. & model & bound & $\\log_{10}\\delta$ & needed \\\\",
  "\\midrule",
  rows,
  "\\bottomrule",
  "\\end{tabular}",
  "\\end{table}")
dir.create("manuscript/tables", showWarnings = FALSE)
writeLines(tex, "manuscript/tables/tab_reduction.tex")
cat("Wrote manuscript/tables/tab_reduction.tex:", nrow(d), "populations\n")
s <- d %>% filter(!is.na(delta))
cat(sprintf("First order N_e/N: median %.2f, min %.2f (%s)\n", median(d$ne_first), min(d$ne_first), d$label[which.min(d$ne_first)]))
cat(sprintf("Multiplicative N_e/N: median %.2f, min %.3f; bound min %.3f\n", median(d$ne_mult), min(d$ne_mult), min(d$ne_bound)))
cat(sprintf("With diversity data (n = %d): 1/delta %s to %s; V_A needed %.2f to %.2f; upper HPD max %.2f\n",
            nrow(s), sig(min(1 / s$delta)), sig(max(1 / s$delta)), min(s$va_need), max(s$va_need), max(s$va_hpd95_hi)))
cat(sprintf("Shortfall of the bound, deficit / bound reduction: %s to %s\n",
            sig(min((1 / s$delta) * s$ne_bound)), sig(max((1 / s$delta) * s$ne_bound))))
